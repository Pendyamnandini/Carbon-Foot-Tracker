// Update TRANSLATIONS languages with newKeys
for (const lang in TRANSLATIONS) {
  for (const [key, defaultVal] of Object.entries(newKeys)) {
    if (!TRANSLATIONS[lang][key]) {
      TRANSLATIONS[lang][key] = defaultVal;
    }
  }
}

// Generate the new file content string
let newContent = 'const TRANSLATIONS = ' + JSON.stringify(TRANSLATIONS, null, 2) + ';\n\n' +
  'export const translate = (key, lang = \'en\') => {\n' +
  '  const dict = TRANSLATIONS[lang] || TRANSLATIONS[\'en\'];\n' +
  '  return dict[key] || TRANSLATIONS[\'en\'][key] || key;\n' +
  '};\n' +
  'export default TRANSLATIONS;\n';

fs.writeFileSync(filepath, newContent, 'utf8');
console.log("Translations successfully updated & expanded!");
